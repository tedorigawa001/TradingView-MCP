test('createRandom reproduces the sequences of the copies it replaced, exactly', () => {
  for (const [seed, expected] of GOLDEN) {
    const random = createRandom(seed);
    assert.deepEqual(Array.from({ length: expected.length }, () => random()), expected, `seed ${seed}`);
  }
});

test('createRandom stays in [0, 1) and treats seeds modulo 2^32', () => {
  const random = createRandom(20260928);
  for (let i = 0; i < 10000; i++) {
    const value = random();
    assert.ok(value >= 0 && value < 1);
  }
  const a = createRandom(2 ** 32 + 5), b = createRandom(5);
  for (let i = 0; i < 5; i++) assert.equal(a(), b());
});
