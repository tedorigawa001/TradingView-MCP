function finish(f) {
  begin(f);
  for (const p of (f.allPairs ?? f.manifest.pairs)) for (const role of ["receipt", "payload"]) { event(f, "move_pending", role,{recording_id:p.recording_id}); event(f, "held_verified", role,{recording_id:p.recording_id}); }
  for (const p of (f.allPairs ?? f.manifest.pairs)) for (const role of ["receipt", "payload"]) {
    event(f, f.intent.kind === "prune" ? "unlink_pending" : "quarantine_move_pending", role,{recording_id:p.recording_id});
    event(f, f.intent.kind === "prune" ? "purged_verified" : "quarantined_verified", role,{recording_id:p.recording_id});
  }
  complete(f); return f;
}
function reseal(f) {
  f.intent.manifests = f.records.filter(r => r.role === "manifest").map(r => ({ chunk_id: r.value.chunk_id, hash: hash(canonical(r.value)) }));
  let previous = null;
  const attempts = new Map();
  for (const r of f.records) {
    if (r.role === "attempt") { r.value.intent_hash = hash(canonical(f.intent)); attempts.set(r.value.attempt_id,r.value); }
    if (["event", "completion"].includes(r.role)) {
      r.value.intent_hash = hash(canonical(f.intent)); r.value.attempt_hash = hash(canonical(attempts.get(r.value.attempt_id)));
      if (r.role === "event") { r.value.previous_event_hash = previous; previous = hash(canonical(r.value)); }
      else r.value.last_event_hash = previous;
    }
  }
}
